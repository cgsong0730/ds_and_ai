import numpy as np

arr = np.array([10, 20, 30, 40, 50, 60, 70])

print(arr[2:5])      # [30 40 50]  → 인덱스 2부터 4까지 (5는 미포함)
print(arr[:3])       # [10 20 30]  → 처음부터 인덱스 2까지
print(arr[3:])       # [40 50 60 70]  → 인덱스 3부터 끝까지
print(arr[::2])      # [10 30 50 70]  → 2칸씩 건너뛰기
print(arr[::-1])     # [70 60 50 40 30 20 10]  → 역순

